def aliases(names: list[str]) -> list[str]:
    result: list[str] = []
    for name in names:
        for spelling in (name, name if name.endswith("-symbolic") else name + "-symbolic"):
            if spelling not in result:
                result.append(spelling)
    return result


def unique_symbols() -> list[tuple[str, bool]]:
    seen: list[tuple[str, bool]] = []
    wanted = [(symbol, fill) for symbol, fill, _context, _names in ICONS]
    wanted += [(symbol, fill) for symbol, fill, _names in APP_ICONS]
    for key in wanted:
        if key not in seen:
            seen.append(key)
    return seen


def contexts() -> list[str]:
    seen: list[str] = []
    for _symbol, _fill, context, _names in ICONS:
        if context not in seen:
            seen.append(context)
    return sorted(seen)


